"""Upload the released data to a Zenodo *draft* deposition (never publishes).

    export ZENODO_TOKEN=...          # personal token, scopes deposit:write
    uv run python scripts/zenodo_upload.py --dry-run
    uv run python scripts/zenodo_upload.py [--sandbox] [--deposition-id ID [--set-metadata]]
        [--replace NAME ...]

Uploads ``data/processed/*.pt``, ``data/processed/manifest.json``, ``LICENSE.md``,
``qgf_raw.tar`` (an uncompressed tar of ``data/raw``; the .npz inside are already
compressed), ``qgf_results.tar`` (the small per-trial/per-cell result files of
``results/`` listed in ``RESULTS``, plus ``scripts/zenodo/results_README.md``), both
built next to the processed files if absent, and the record ``README.md`` and
``MANIFEST.csv`` (generated by ``scripts/zenodo/build_record_files.py``). Files already in
the draft with the same md5 are skipped; ``--replace NAME...`` first deletes those named
draft files (only files this script uploads). With ``--deposition-id`` the record metadata is
left untouched unless ``--set-metadata`` is given. Review and publish the draft from the
Zenodo web interface.
"""

import argparse
import hashlib
import json
import os
import sys
import tarfile
from pathlib import Path
from urllib.parse import quote
from urllib.request import Request, urlopen

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts" / "zenodo"))
from build_record_files import build  # noqa: E402

METADATA = {
    "title": (
        "Neutral-Atom Quantum Features as Complementary Structural Encodings for "
        "Graph Learning: datasets"
    ),
    "upload_type": "dataset",
    "description": (
        "Quantum graph features (connected Rydberg-occupation correlations, ZZ convention) "
        "for MUTAG and ZINC*_subset, emulated and QPU, with the raw measurement counts. "
        "Code: the qgf repository. Licence: Pasqal open-source licence (LICENSE.md)."
    ),
    "creators": [
        {"name": name, "affiliation": "Pasqal, France"}
        for name in (
            "Garrigues, Mathieu",
            "Sokolov, Igor",
            "Hecker, Matthias",
            "Moro, Lorenzo",
            "Acheche, Shaheen",
        )
    ],
    "access_right": "open",
    # ponytail: Zenodo has no id for the Pasqal licence; the text ships as LICENSE.md.
}


def api(base: str, token: str, method: str, path: str, body=None, size=None) -> dict:
    url = path if path.startswith("http") else base + path
    headers = {"Authorization": f"Bearer {token}"}
    if isinstance(body, dict):
        body = json.dumps(body).encode()
        headers["Content-Type"] = "application/json"
    elif body is not None:
        headers["Content-Type"] = "application/octet-stream"
        headers["Content-Length"] = str(size)
    with urlopen(Request(url, data=body, headers=headers, method=method)) as response:
        data = response.read()
    return json.loads(data) if data else {}  # DELETE answers 204 without a body


# (directory under results/, name inside qgf_results.tar, glob); only these suffixes ship.
