def write_tables(results_dir: str, out_dir: str, latex: bool = False) -> list[str]:
    results = load_results(results_dir)
    os.makedirs(out_dir, exist_ok=True)
    datasets = sorted({r["dataset"] for r in results})
    files: dict[str, str] = {}
    for ds in datasets:
        files[f"{ds}_table_full.md"] = generate_md_table_full(results, ds)
        if latex:
            label = "tab:pe-benchmark-mutag" if ds == "MUTAG" else "tab:pe-benchmark"
            files[f"{ds}_table_full.tex"] = generate_latex_table(results, ds, label=label)
    if "ZINC_small" in datasets:
        files["ZINC_small_table_main.md"] = generate_md_table_main(results, "ZINC_small")
        tex, md = quantum_comparison(results)
        files["ZINC_quantum_comparison.md"] = md
        files["ZINC_residual_comparison.md"] = residual_comparison(results)
        if latex:
            files["ZINC_small_table_main.tex"] = generate_latex_table_main(results, "ZINC_small")
            files["ZINC_quantum_comparison.tex"] = tex
    for name, content in files.items():
        with open(os.path.join(out_dir, name), "w") as f:
            f.write(content)
    return sorted(files)


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(description="Intrinsic benchmark tables")
    parser.add_argument("--results_dir", required=True)
    parser.add_argument("--out_dir", required=True)
    parser.add_argument("--latex", action="store_true", help="also write .tex tables")
    args = parser.parse_args(argv)
    for name in write_tables(args.results_dir, args.out_dir, args.latex):
        print(os.path.join(args.out_dir, name))


if __name__ == "__main__":
    main()
