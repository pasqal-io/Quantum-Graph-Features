def generate_latex_table(
    results: list[dict],
    dataset_name: str,
    label: str = "tab:pe-benchmark",
) -> str:
    data: dict = {}
    for r in results:
        if r["dataset"] != dataset_name:
            continue
        cat = _CATEGORY_REMAP.get(r["category"], r["category"])
        data[(cat, r["benchmark"], r["pe_type"])] = r

    present = {key[2] for key in data}

    groups: list[tuple[str, list[str]]] = [
        (gname, [f for f in gpes if f in present]) for gname, gpes in _PE_LEGEND_GROUPS
    ]
    groups = [(gname, gpes) for gname, gpes in groups if gpes]

    # Split groups: top (Baseline+Classical+FM), bottom (AFM+Hybrid)
    split = (len(groups) + 1) // 2
    groups_top = groups[:split]
    groups_bot = groups[split:]

    all_feats = [f for _, gpes in groups for f in gpes]
    benchmark_scales = _precompute_scales(data, all_feats)

    # Pre-compute global rankings restricted to shown features (both halves combined).
    # Using subset avoids ranking against hidden features (e.g. GS variants in MUTAG).
    all_feats_set = set(all_feats)
    global_rankings: dict = {}
    for _cat, _bms in CATEGORIES_ORDERED.items():
        for _bm in _bms:
            global_rankings[(_cat, _bm)] = _rank_features(
                data,
                _cat,
                _bm,
                _bm in _CLASSIFICATION_BENCHMARKS,
                subset=all_feats_set,
            )

    display_name = r"ZINC$_{\text{subset}}^{*}$" if "ZINC" in dataset_name else dataset_name

    def _build_subtable(groups_sub: list[tuple[str, list[str]]]) -> list[str]:
        feats_sub = [f for _, gpes in groups_sub for f in gpes]
        col_spec = "l " + " ".join("c" * len(gpes) for _, gpes in groups_sub)
        n_total_cols = sum(len(gpes) for _, gpes in groups_sub) + 1

        sub = [
            r"  \resizebox{\textwidth}{!}{%",
            f"  \\begin{{tabular}}{{{col_spec}}}",
            r"    \toprule",
        ]

        hdr1 = "    "
        col_cursor = 2
        cmidrules = []
        for gname, gpes in groups_sub:
            n = len(gpes)
            hdr1 += f"& \\multicolumn{{{n}}}{{c}}{{{gname}}} "
            cmidrules.append(f"\\cmidrule(lr){{{col_cursor}-{col_cursor + n - 1}}}")
            col_cursor += n
        sub.append(hdr1 + r"\\")
        sub.append("    " + " ".join(cmidrules))

        hdr2 = "    Task"
        for _, gpes in groups_sub:
            for f in gpes:
                hdr2 += f"\n    & {PE_LABELS.get(f, f)}"
        sub.append(hdr2 + "\n    \\\\")
        sub.append(r"    \midrule")

        first_cat = True
        for category, benchmarks in CATEGORIES_ORDERED.items():
            if not first_cat:
                sub.append(r"    \addlinespace[2pt]\midrule\addlinespace[1pt]")
            first_cat = False
            sub.append(
                f"    \\multicolumn{{{n_total_cols}}}{{l}}"
                f"{{\\textit{{{CATEGORY_LABELS[category]}}}}}\\\\",
            )
            n_acc = _ACCURACY_COUNT.get(category, 0)

            for i, benchmark in enumerate(benchmarks):
                if i == n_acc and n_acc > 0:
                    sub.append(r"    \specialrule{0.4pt}{1pt}{1pt}")

                is_cls = benchmark in _CLASSIFICATION_BENCHMARKS
                entries = {
                    f: (
                        data[(category, benchmark, f)]["raw_value"],
                        data[(category, benchmark, f)].get("std_dev") or 0.0,
                    )
                    for f in feats_sub
                    if (category, benchmark, f) in data
                }
                scale, scale_suffix = benchmark_scales.get((category, benchmark), (1.0, ""))
                best_feat, second_feat, tied_set = global_rankings[(category, benchmark)]

                metric_str = r"Acc $\uparrow$" if is_cls else r"MAE $\downarrow$"
                row = (
                    f"    {BENCHMARK_LABELS.get(benchmark, benchmark)} ({metric_str}){scale_suffix}"
                )
                feats_sub_set = set(feats_sub)
                local_tied = tied_set & feats_sub_set
                has_tied_group = len(local_tied) > 1

                for f in feats_sub:
                    if f in entries:
                        val, std = entries[f]
                        if f in local_tied and has_tied_group:
                            # Multiple tied peers visible in this half → \tied
                            cell = _make_cell(val, std, scale, False, False, True)
                        elif f in local_tied:
                            # Sole tied feature in this half: fall back to global rank
                            cell = _make_cell(
                                val,
                                std,
                                scale,
                                f == best_feat,
                                f == second_feat,
                                False,
                            )
                        else:
                            cell = _make_cell(
                                val,
                                std,
                                scale,
                                f == best_feat and not tied_set,
                                f == second_feat and not tied_set,
                                False,
                            )
                        row += f"\n    & {cell}"
                    else:
                        row += "\n    & ---"
                sub.append(row + "\n    \\\\")

        sub += [r"    \bottomrule", r"  \end{tabular}", r"  }"]
        return sub

    lines = [r"\begin{table*}"]
    lines += [
        r"\caption{",
        f"  Intrinsic information benchmark on {display_name} graph tasks.",
        r"  Mean~${\pm}$~standard deviation over 5-fold cross-validation.",
        _RANKING_CAPTION_NOTE,
        r"  $^\downarrow$ MAE (lower is better), $^\uparrow$ Accuracy (higher is better).",
        r"}",
        f"\\label{{{label}}}",
        r"\centering",
    ]
    lines += _build_subtable(groups_top)
    lines.append(r"\par\medskip")
    lines += _build_subtable(groups_bot)
    lines.append(r"\end{table*}")

    return "\n".join(lines)


