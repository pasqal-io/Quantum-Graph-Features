def _fmt_val(val: float, std: float, scale: float) -> tuple[str, str]:
    v, s = val * scale, std * scale
    if s >= 10:
        return f"{v:.0f}", f"{s:.0f}"
    elif s >= 1:
        return f"{v:.1f}", f"{s:.1f}"
    else:
        return f"{v:.2f}", f"{s:.2f}"


def _fmt_main(val: float, scale: float) -> str:
    """3-sig-fig formatting for the no-std main table."""
    v = val * scale
    if v == 0:
        return "0"
    mag = int(floor(log10(abs(v))))
    if mag >= 2:
        decimals = 0
    elif mag == 1:
        decimals = 1
    else:
        decimals = 2
    return f"{v:.{decimals}f}"


def _make_cell(
    val: float,
    std: float,
    scale: float,
    is_best: bool = False,
    is_second: bool = False,
    is_tied: bool = False,
) -> str:
    v_str, s_str = _fmt_val(val, std, scale)
    if is_tied:
        return f"$\\tied{{{v_str}}}{{_{{\\pm {s_str}}}}}$"
    if is_best:
        return f"$\\best{{{v_str}}}{{_{{\\pm {s_str}}}}}$"
    elif is_second:
        return f"$\\second{{{v_str}}}{{_{{\\pm {s_str}}}}}$"
    return f"${v_str}{{_{{\\pm {s_str}}}}}$"


def _make_cell_main(
    val: float,
    scale: float,
    is_best: bool = False,
    is_second: bool = False,
    is_tied: bool = False,
) -> str:
    v_str = _fmt_main(val, scale)
    if is_tied:
        return f"$\\tied{{{v_str}}}$"
    if is_best:
        return f"$\\best{{{v_str}}}$"
    elif is_second:
        return f"$\\second{{{v_str}}}$"
    return f"${v_str}$"


def _auto_scale(values: list[float]) -> tuple[float, str]:
    if not values:
        return 1.0, ""
    # Use minimum (best-case value) as the scale driver: if the best feature
    # achieves small values, we rescale so the entire row is readable at that
    # resolution. Using the mean would suppress scaling when a few bad features
    # have large values.
    mn = float(np.min(np.abs(values)))
    if mn == 0:
        return 1.0, ""
    if mn < 0.01:
        return 1e3, r" ($\times 10^{3}$)"
    if mn < 0.1:
        return 1e2, r" ($\times 10^{2}$)"
    return 1.0, ""


def _rank_features(
    data: dict,
    category: str,
    benchmark: str,
    higher_is_better: bool,
    subset: set[str] | None = None,
) -> tuple[str | None, str | None, set[str]]:
    """Returns (best, second, tied_set).

    tied_set contains all features within best's own uncertainty:
      |v_best - v_f| <= std_best + 0.005 * |v_best|
    The relative epsilon scales with the metric (accuracy v~1 → tol~0.015 ;
    small-MAE v~0.005 → tol~0.000075), ensuring no false ties on small-scale tasks.
    Excludes 'random'. If subset is given, restricts ranking to those features.
    """
    entries = {
        key[2]: (data[key]["raw_value"], data[key].get("std_dev") or 0.0)
        for key in data
        if key[0] == category
        and key[1] == benchmark
        and key[2] != "random"
        and (subset is None or key[2] in subset)
    }
    if not entries:
        return None, None, set()

    ranked = sorted(
        entries,
        key=lambda f: -entries[f][0] if higher_is_better else entries[f][0],
    )
    best = ranked[0]
    second = ranked[1] if len(ranked) >= 2 else None

    val_best, std_best = entries[best]
    threshold = std_best + 0.005 * abs(val_best)

    tied_set: set[str] = set()
    if second is not None:
        val_second, _ = entries[second]
        if abs(val_best - val_second) <= threshold:
            for f, (val, _) in entries.items():
                if abs(val_best - val) <= threshold:
                    tied_set.add(f)

    return best, second, tied_set


def _precompute_scales(
    data: dict,
    feats: list[str],
) -> dict[tuple[str, str], tuple[float, str]]:
    """Compute _auto_scale for every (category, benchmark) across ALL listed features.

    Using all features ensures both halves of a split table share the same multiplier.
    """
    scales: dict[tuple[str, str], tuple[float, str]] = {}
    for cat, benchmarks in CATEGORIES_ORDERED.items():
        for bm in benchmarks:
            vals = [data[(cat, bm, f)]["raw_value"] for f in feats if (cat, bm, f) in data]
            scales[(cat, bm)] = _auto_scale(vals)
    return scales


