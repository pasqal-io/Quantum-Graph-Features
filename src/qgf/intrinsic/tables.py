def load_results(results_dir: str) -> list[dict]:
    """All ``<dataset>/<pe_type>/<task>/result.json`` of the paper benchmark under ``results_dir``.

    The PE type is taken from the directory name, not from the json: the original
    loader keyed on the json ``pe_type``, so a renamed stale run (``HW_AFM_before``,
    whose json says ``HW_AFM``) could silently replace the current one.
    """
    results = []
    for root, _, files in os.walk(results_dir):
        if "result.json" in files:
            with open(os.path.join(root, "result.json")) as f:
                r = json.load(f)
            pe_dir = os.path.basename(os.path.dirname(os.path.normpath(root)))
            if (
                r["dataset"] in DATASETS
                and pe_dir == r["pe_type"]
                and r["pe_type"] in PE_TYPES
                and r["benchmark"] in BENCHMARK_LABELS
            ):
                results.append(r)
    return results


