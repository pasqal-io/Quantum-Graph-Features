def _md_label(f: str) -> str:
    return (
        PE_LABELS.get(f, f)
        .replace(r"$_\mu$", "_mean")
        .replace(r"$_{\mathrm{stat}}$", "_stat")
        .replace(r"$_\mathrm{res}$", "_res")
    )


def _md_scale(suffix: str) -> str:
    return suffix.replace(r" ($\times 10^{3}$)", " (×10³)").replace(
        r" ($\times 10^{2}$)", " (×10²)"
    )


def _md_mark(text: str, f: str, best, second, tied_set) -> str:
    if f in tied_set:
        return f"{text} ≈"
    if f == best and not tied_set:
        return f"**{text}**"
    if f == second and not tied_set:
        return f"*{text}*"
    return text


_MD_LEGEND = (
    "**bold**: best, *italic*: runner-up, ≈: statistically tied with the best "
    "(|v_best − v| ≤ σ_best + 0.005·|v_best|). ↓ MAE, ↑ accuracy. Random is not ranked."
)


def _by_key(results, dataset_name):
    data = {}
    for r in results:
        if r["dataset"] == dataset_name:
            cat = _CATEGORY_REMAP.get(r["category"], r["category"])
            data[(cat, r["benchmark"], r["pe_type"])] = r
    return data


def _md_table(results, dataset_name, cols, with_std: bool, title: str) -> str:
    data = _by_key(results, dataset_name)
    present = {k[2] for k in data}
    cols = [f for f in cols if f in present]
    scales = _precompute_scales(data, cols)
    lines = [f"# {title}", "", _MD_LEGEND, ""]
    lines.append("| Task | " + " | ".join(_md_label(f) for f in cols) + " |")
    lines.append("|---" * (len(cols) + 1) + "|")
    for category, benchmarks in CATEGORIES_ORDERED.items():
        lines.append(f"| *{CATEGORY_LABELS[category]}* |" + " |" * len(cols))
        for bm in benchmarks:
            is_cls = bm in _CLASSIFICATION_BENCHMARKS
            scale, suffix = scales.get((category, bm), (1.0, ""))
            best, second, tied = _rank_features(data, category, bm, is_cls, subset=set(cols))
            row = f"| {BENCHMARK_LABELS[bm]} {'↑' if is_cls else '↓'}{_md_scale(suffix)} |"
            for f in cols:
                r = data.get((category, bm, f))
                if r is None:
                    row += " — |"
                    continue
                if with_std:
                    v, s = _fmt_val(r["raw_value"], r.get("std_dev") or 0.0, scale)
                    text = f"{v} ± {s}"
                else:
                    text = _fmt_main(r["raw_value"], scale)
                row += f" {_md_mark(text, f, best, second, tied)} |"
            lines.append(row)
    return "\n".join(lines) + "\n"


def generate_md_table_full(results, dataset_name) -> str:
    cols = [f for _, g in _PE_LEGEND_GROUPS for f in g]
    name = "ZINC*_subset" if "ZINC" in dataset_name else dataset_name
    title = f"Intrinsic information benchmark on {name} (mean ± std over 5 folds)"
    return _md_table(results, dataset_name, cols, True, title)


def generate_md_table_main(results, dataset_name) -> str:
    name = "ZINC*_subset" if "ZINC" in dataset_name else dataset_name
    title = f"Intrinsic information benchmark on {name} (main table, means over 5 folds)"
    return _md_table(results, dataset_name, _MAIN_PE_COLS, False, title)


# ── Strengthened-baseline and residual comparisons (mean ± SE, SE = std/√5) ──

SR5 = math.sqrt(5)
LEAK = {"smallest_cycle_node", "smallest_cycle_edge", "num_cycles"}
ROWS = [
    ("degree_prediction", "Degree"),
    ("betweenness_prediction", "Betweenness"),
    ("bridge_node_prediction", "Bridge Node"),
    ("node_eccentricity", "Eccentricity"),
    ("smallest_cycle_node", "Min Cycle (Node)"),
    ("link_prediction", "Link Pred."),
    ("edge_betweenness", "Edge Betw."),
    ("smallest_cycle_edge", "Min Cycle (Edge)"),
    ("is_bridge_edge", "Bridge Edge"),
    ("local_edge_connectivity", "Local Conn."),
    ("num_cycles", "Num Cycles"),
    ("graph_diameter", "Diameter"),
    ("graph_density", "Density"),
    ("wiener_index", "Wiener Index"),
    ("algebraic_connectivity", "Alg. Connect."),
]
QUANTUM_COMPARISON = {
    "RRWP_Laplacian_Ring": "RRWP+L+Ring",
    "RRWP_FM_AFM": "RRWP+FM+AFM",
    "RRWP_Laplacian_Ring_Quantum": "RRWP+L+Ring+Q",
    "RRWP_Laplacian_Ring_Geometric": "RRWP+L+Ring+Geo",
    "RRWP_Laplacian_Ring_Geometric_Quantum": "RRWP+L+Ring+Geo+Q",
}
RESIDUAL_COMPARISON = {
    "RRWP_Laplacian": "RRWP+L",
    "RRWP_FM_AFM": "RRWP+L+AFM+FM",
    "RRWP_Laplacian_Ring_Geometric": "RRWP+L+R+G",
    "RRWP_Laplacian_Ring_Geometric_Quantum": "RRWP+L+R+G+AFM+FM",
    "RRWP_Laplacian_Ring_Geometric_FMres_AFMres": "RRWP+L+R+G+Both res.",
}
_RING_PES = {pe for pe in PE_TYPES if "_Ring" in pe}


def _compute_comparison(results, dataset_name, pes):
    """Per task: cells {pe: (v, se) | ("leak"|"running", None)}, winner label, winner pe."""
    data = {(r["pe_type"], r["benchmark"]): r for r in results if r["dataset"] == dataset_name}
    computed = []
    for bkey, blabel in ROWS:
        cells, metric = {}, None
        for pe in pes:
            r = data.get((pe, bkey))
            if bkey in LEAK and pe in _RING_PES:
                cells[pe] = ("leak", None)
            elif r is None:
                cells[pe] = ("running", None)
            else:
                cells[pe] = (r["raw_value"], r["std_dev"] / SR5)
                metric = r["metric"]
        higher = metric == "accuracy"
        cand = {pe: cells[pe] for pe in pes if isinstance(cells[pe][0], float)}
        winpe = None
        if len(cand) >= 2:
            items = sorted(cand.items(), key=lambda kv: kv[1][0], reverse=higher)
            (bpe, (bv, bse)), (_, (sv, sse)) = items[0], items[1]
            disjoint = (bv - bse) > (sv + sse) if higher else (bv + bse) < (sv - sse)
            winpe = bpe if disjoint else None
            winner = pes[bpe] if disjoint else None
        elif len(cand) == 1:
            winner = "(only one)"
        else:
            winner = "(running)"
        computed.append((blabel, higher, cells, winner, winpe))
    return computed


def _comparison_tex(computed, pes) -> str:
    """LaTeX of the strengthened-baseline comparison (as gen_zinc_quantum_comparison.py)."""
    lines = [
        r"\begin{table}[t]",
        r"\centering",
        r"\small",
        r"\setlength{\tabcolsep}{4pt}",
        r"\caption{ZINC: PE quality (mean $\pm$ standard error over 5 folds). "
        r"Cycle-related benchmarks leak the ring encoding (\emph{leak}). A per-row "
        r"winner is declared only when there is no statistical tie (disjoint "
        r"$\pm 1$~SE bars).}",
        r"\label{tab:zinc_quantum}",
        r"\begin{tabular}{l" + "l" + "c" * len(pes) + " l}",
        r"\toprule",
        "Benchmark & Metric & " + " & ".join(pes.values()) + " & Winner \\\\",
        r"\midrule",
    ]
    for blabel, higher, cells, winner, winpe in computed:
        md = "Acc$\\uparrow$" if higher else "MAE$\\downarrow$"
        parts = []
        for pe in pes:
            v, se = cells[pe]
            if isinstance(v, str):
                parts.append(f"\\emph{{{v}}}")
            else:
                s = f"{v:.3f} $\\pm$ {se:.3f}"
                parts.append(f"\\textbf{{{s}}}" if pe == winpe else s)
        lines.append(f"{blabel} & {md} & " + " & ".join(parts) + f" & {winner or 'tie'} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def _comparison_md(computed, pes, tie_label, bold_winner) -> str:
    lines = [
        "| Benchmark | Metric | " + " | ".join(pes.values()) + " | Winner |",
        "|---|---|" + "---|" * len(pes) + "---|",
    ]
    for blabel, higher, cells, winner, winpe in computed:
        mu = "Acc↑" if higher else "MAE↓"
        parts = []
        for pe in pes:
            v, se = cells[pe]
            if isinstance(v, str):
                parts.append(f"*{v}*")
            else:
                s = f"{v:.3f} ± {se:.3f}"
                parts.append(f"**{s}**" if pe == winpe else s)
        w = winner or tie_label
        w = f"**{w}**" if bold_winner else w
        lines.append(f"| {blabel} | {mu} | " + " | ".join(parts) + f" | {w} |")
    return "\n".join(lines) + "\n"


def quantum_comparison(results, dataset_name="ZINC_small") -> tuple[str, str]:
    """Strengthened-baseline comparison: (tex, md), as gen_zinc_quantum_comparison.py."""
    computed = _compute_comparison(results, dataset_name, QUANTUM_COMPARISON)
    return (
        _comparison_tex(computed, QUANTUM_COMPARISON),
        _comparison_md(computed, QUANTUM_COMPARISON, "tie", bold_winner=True),
    )


RESIDUAL_HEADER = """# ZINC — residual PE comparison

Mean ± standard error over 5 folds. A winner is declared only when the ±1 SE bars
of the two best columns are disjoint, otherwise *statistical tie*. Cycle benchmarks
leak the ring encoding (*leak*) for the R+G columns.

*Note: `RRWP+L+AFM+FM` is `RRWP_FM_AFM` (RRWP+FM+AFM); no separate Laplacian block exists for it.*

"""


def residual_comparison(results, dataset_name="ZINC_small") -> str:
    """Residual comparison table (markdown), same winner rule as the quantum comparison."""
    computed = _compute_comparison(results, dataset_name, RESIDUAL_COMPARISON)
    return RESIDUAL_HEADER + _comparison_md(
        computed, RESIDUAL_COMPARISON, "statistical tie", bold_winner=False
    )


